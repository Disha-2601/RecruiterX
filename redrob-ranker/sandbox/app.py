import streamlit as st
import pandas as pd
import os

st.set_page_config(page_title="Redrob Ranker Sandbox", layout="wide")

st.title("🎯 Redrob Ranker Sandbox")
st.subheader("Visual transparency tool for the top 100 ranked candidates")
st.write("This dashboard displays the final ranked list of candidates generated by our vectorized inference engine.")

# Path resolution for local running or spaces deployment
csv_path = "submission.csv"
if not os.path.exists(csv_path):
    csv_path = os.path.join(os.path.dirname(__file__), "..", "submission.csv")

if os.path.exists(csv_path):
    df = pd.read_csv(csv_path)
    
    col1, col2 = st.columns(2)
    with col1:
        st.metric("Total Ranked Candidates", len(df))
    with col2:
        search_query = st.text_input("🔍 Search Candidate ID", "")
        
    if search_query:
        df_display = df[df["candidate_id"].str.contains(search_query, case=False)]
    else:
        df_display = df
        
    st.dataframe(
        df_display,
        column_config={
            "candidate_id": st.column_config.TextColumn("Candidate ID", help="Unique identifier of the candidate"),
            "rank": st.column_config.NumberColumn("Rank", help="System-assigned rank (1-100)"),
            "score": st.column_config.NumberColumn("Score", format="%.4f", help="Weighted final composite score (0-1)"),
            "reasoning": st.column_config.TextColumn("Factual Reasoning", help="Deterministic reasoning breakdown")
        },
        hide_index=True,
        use_container_width=True
    )
else:
    st.warning("No submission.csv found. Please run the ranking orchestration pipeline first to generate the results.")
